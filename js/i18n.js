function getI18nSystemLanguage() {
  const uiLanguage = (chrome.i18n?.getUILanguage?.() || navigator.language || "en").replace("-", "_");
  if (I18N_SUPPORTED_LANGUAGES[uiLanguage]) {
    return uiLanguage;
  }
  const shortLanguage = uiLanguage.split("_")[0];
  return I18N_SUPPORTED_LANGUAGES[shortLanguage] ? shortLanguage : "en";
}

function normalizeI18nLanguage(language) {
  if (!language || language === "system") {
    return getI18nSystemLanguage();
  }
  return I18N_SUPPORTED_LANGUAGES[language] ? language : "en";
}

function translateText(value, language) {
  const text = String(value || "").trim();
  if (!text) {
    return value;
  }
  return I18N_PHRASES[language]?.[text] || I18N_PHRASES.en[text] || translateTextByRule(text, language) || value;
}

function translateNodeText(node, language) {
  const currentText = node.textContent.trim();
  if (!currentText) {
    return;
  }

  if (!node.dataset.i18nSource || (node.dataset.i18nTranslatedValue && currentText !== node.dataset.i18nTranslatedValue)) {
    node.dataset.i18nSource = currentText;
  }
  const translated = translateText(node.dataset.i18nSource, language);
  node.dataset.i18nTranslatedValue = translated;
  if (translated !== currentText) {
    node.textContent = translated;
  }
}

function translateAttribute(node, attribute, sourceKey, translatedKey, language) {
  const currentValue = node.getAttribute(attribute);
  if (!currentValue) {
    return "";
  }
  if (!node.dataset[sourceKey] || (node.dataset[translatedKey] && currentValue !== node.dataset[translatedKey])) {
    node.dataset[sourceKey] = currentValue;
  }
  const translated = translateText(node.dataset[sourceKey], language);
  node.dataset[translatedKey] = translated;
  if (translated !== currentValue) {
    node.setAttribute(attribute, translated);
  }
  return translated;
}

function translateTooltip(node, attribute, sourceKey, translatedKey, language) {
  const currentValue = node.getAttribute(attribute) || node.dataset.appTooltip;
  if (!currentValue) {
    return;
  }
  if (!node.dataset[sourceKey] || (node.dataset[translatedKey] && currentValue !== node.dataset[translatedKey])) {
    node.dataset[sourceKey] = currentValue;
  }
  const translated = translateText(node.dataset[sourceKey], language);
  node.dataset[translatedKey] = translated;
  node.dataset.appTooltip = translated;

  if (!node.getAttribute("aria-label")) {
    node.setAttribute("aria-label", translated);
  }

  if (attribute === "title") {
    node.removeAttribute("title");
  } else {
    node.setAttribute(attribute, translated);
  }
}

function refreshBootstrapTooltip(node) {
  const Tooltip = window.bootstrap?.Tooltip;
  if (!Tooltip) {
    return;
  }
  const instance = Tooltip.getInstance?.(node);
  if (!instance) {
    return;
  }
  instance.dispose();
}

function getTooltipElement() {
  let tooltip = document.querySelector(".app-tooltip");
  if (!tooltip) {
    tooltip = document.createElement("div");
    tooltip.className = "app-tooltip";
    tooltip.setAttribute("role", "tooltip");
    tooltip.innerHTML = '<span class="app-tooltip-text"></span>';
    document.body.appendChild(tooltip);
  }
  return tooltip;
}

function positionTooltip(tooltip, target) {
  const rect = target.getBoundingClientRect();
  const tooltipRect = tooltip.getBoundingClientRect();
  const gap = 10;
  const viewportPadding = 10;
  const topSpace = rect.top;
  const shouldShowBelow = topSpace < tooltipRect.height + gap + viewportPadding;
  const top = shouldShowBelow ? rect.bottom + gap : rect.top - tooltipRect.height - gap;
  const idealLeft = rect.left + (rect.width - tooltipRect.width) / 2;
  const left = Math.min(
    Math.max(idealLeft, viewportPadding),
    window.innerWidth - tooltipRect.width - viewportPadding
  );

  tooltip.dataset.placement = shouldShowBelow ? "bottom" : "top";
  tooltip.style.left = `${left}px`;
  tooltip.style.top = `${Math.max(viewportPadding, top)}px`;
}

function showCustomTooltip(target) {
  if (!currentShowTooltips) {
    return;
  }
  const text = target.dataset.appTooltip;
  if (!text) {
    return;
  }
  const tooltip = getTooltipElement();
  tooltip.querySelector(".app-tooltip-text").textContent = text;
  tooltip.dataset.visible = "true";
  positionTooltip(tooltip, target);
}

function hideCustomTooltip() {
  const tooltip = document.querySelector(".app-tooltip");
  if (tooltip) {
    tooltip.dataset.visible = "false";
  }
}

function installCustomTooltips() {
  if (document.documentElement.dataset.customTooltipsReady) {
    return;
  }
  document.documentElement.dataset.customTooltipsReady = "true";

  document.addEventListener("pointerover", (event) => {
    const target = event.target.closest("[data-app-tooltip]");
    if (target) {
      showCustomTooltip(target);
    }
  });

  document.addEventListener("pointerout", (event) => {
    if (event.target.closest("[data-app-tooltip]")) {
      hideCustomTooltip();
    }
  });

  document.addEventListener("focusin", (event) => {
    const target = event.target.closest("[data-app-tooltip]");
    if (target) {
      showCustomTooltip(target);
    }
  });

  document.addEventListener("focusout", (event) => {
    if (event.target.closest("[data-app-tooltip]")) {
      hideCustomTooltip();
    }
  });

  window.addEventListener("scroll", hideCustomTooltip, true);
  window.addEventListener("resize", hideCustomTooltip);
}

function applyTooltipPreference(showTooltips = true) {
  currentShowTooltips = showTooltips !== false;
  document.documentElement.dataset.tooltips = currentShowTooltips ? "enabled" : "disabled";
  if (!currentShowTooltips) {
    hideCustomTooltip();
  }
}

function shouldSkipNodeText(node) {
  return Boolean(node.closest(".link-title, .link-url, .link-preview"));
}

function applyI18n(languageSetting = "system") {
  currentI18nLanguageSetting = languageSetting;
  isApplyingI18n = true;
  const language = normalizeI18nLanguage(languageSetting);
  const previousLanguage = lastAppliedI18nLanguage;
  lastAppliedI18nLanguage = language;
  document.documentElement.lang = language.replace("_", "-");
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  if (!i18nDocumentTitleSource || (i18nDocumentTitleTranslated && document.title !== i18nDocumentTitleTranslated)) {
    i18nDocumentTitleSource = document.title;
  }
  i18nDocumentTitleTranslated = translateText(i18nDocumentTitleSource, language);
  document.title = i18nDocumentTitleTranslated;

  if (language !== "en" || (previousLanguage && previousLanguage !== "en")) {
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      const key = node.dataset.i18n;
      node.textContent = I18N_PHRASES[language]?.[key] || key;
    });

    document.querySelectorAll("button, a, span, strong, label, option, h1, h2, h3, h4, small, p, th, td, legend, figcaption, li, #healthProgress, #crawlProgress, #crawlStatus, #resultSummary").forEach((node) => {
      if (node.children.length === 0 && !shouldSkipNodeText(node)) {
        translateNodeText(node, language);
      }
    });
  }

  document.querySelectorAll("[title], [data-app-tooltip]").forEach((node) => {
    translateTooltip(node, "title", "i18nTitleSource", "i18nTitleTranslated", language);
    refreshBootstrapTooltip(node);
  });

  document.querySelectorAll("[data-bs-original-title]").forEach((node) => {
    translateTooltip(node, "data-bs-original-title", "i18nBootstrapTitleSource", "i18nBootstrapTitleTranslated", language);
    refreshBootstrapTooltip(node);
  });

  if (language !== "en" || (previousLanguage && previousLanguage !== "en")) {
    document.querySelectorAll("[aria-label]").forEach((node) => {
      translateAttribute(node, "aria-label", "i18nAriaSource", "i18nAriaTranslated", language);
    });

    document.querySelectorAll("[placeholder]").forEach((node) => {
      translateAttribute(node, "placeholder", "i18nPlaceholderSource", "i18nPlaceholderTranslated", language);
    });
  }
  installCustomTooltips();
  isApplyingI18n = false;
}

function scheduleI18nRefresh() {
  if (isApplyingI18n) {
    return;
  }
  clearTimeout(i18nRefreshTimer);
  i18nRefreshTimer = setTimeout(() => {
    applyI18n(currentI18nLanguageSetting);
  }, 140);
}

function observeI18nMutations() {
  if (i18nObserver || !document.body) {
    return;
  }
  i18nObserver = new MutationObserver(scheduleI18nRefresh);
  i18nObserver.observe(document.body, {
    childList: true,
    subtree: true,
    attributes: true,
    attributeFilter: ["title", "aria-label", "placeholder", "data-bs-original-title"]
  });
}

function loadI18n() {
  chrome.storage.local.get("extensionSettings", (data) => {
    const settings = data.extensionSettings || {};
    currentI18nLanguageSetting = settings.language || "system";
    applyTooltipPreference(settings.showTooltips);
    applyI18n(currentI18nLanguageSetting);
    observeI18nMutations();
  });
}

chrome.storage.onChanged.addListener((changes, areaName) => {
  if (areaName === "local" && changes.extensionSettings) {
    const settings = changes.extensionSettings.newValue || {};
    currentI18nLanguageSetting = settings.language || "system";
    applyTooltipPreference(settings.showTooltips);
    applyI18n(currentI18nLanguageSetting);
  }
});

window.AllLinksI18n = {
  supported: I18N_SUPPORTED_LANGUAGES,
  apply: applyI18n,
  t: (value) => translateText(value, normalizeI18nLanguage(currentI18nLanguageSetting)),
  load: loadI18n
};

loadI18n();
